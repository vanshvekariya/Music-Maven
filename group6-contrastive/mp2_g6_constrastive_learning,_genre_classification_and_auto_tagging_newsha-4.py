def extract_features(audio_path):
    """Extract multiple audio features for SVM"""
    try:
        # Load audio with error handling
        y, sr = librosa.load(audio_path, sr=22050, duration=30, res_type='kaiser_fast')

        # Ensure minimum length
        if len(y) < sr:  # Less than 1 second
            return None

        # Mel spectrogram
        mel = librosa.feature.melspectrogram(y=y, sr=sr, n_mels=128)
        mel_db = librosa.power_to_db(mel, ref=np.max)

        # MFCCs
        mfcc = librosa.feature.mfcc(y=y, sr=sr, n_mfcc=20)  # Reduced from 40

        # Chroma
        chroma = librosa.feature.chroma_stft(y=y, sr=sr)

        # Spectral features
        spectral_centroid = librosa.feature.spectral_centroid(y=y, sr=sr)
        spectral_rolloff = librosa.feature.spectral_rolloff(y=y, sr=sr)
        zcr = librosa.feature.zero_crossing_rate(y)

        # Rhythm features
        tempo, _ = librosa.beat.beat_track(y=y, sr=sr)

        # Compute statistics for all features
        features = []

        # Single-row features
        for feat in [spectral_centroid, spectral_rolloff, zcr]:
            features.extend([
                float(np.mean(feat)),
                float(np.std(feat)),
                float(np.max(feat)),
                float(np.min(feat))
            ])

        # Multi-row features
        for feat in [mel_db, mfcc, chroma]:
            features.extend([
                float(np.mean(feat)),
                float(np.std(feat)),
                float(np.max(feat)),
                float(np.min(feat))
            ])

        # Add tempo
        features.append(float(tempo))

        # Convert to numpy array
        feature_array = np.array(features, dtype=np.float32)

        # Check for NaN or Inf
        if np.any(np.isnan(feature_array)) or np.any(np.isinf(feature_array)):
            return None

        return feature_array

    except Exception as e:
        return None


