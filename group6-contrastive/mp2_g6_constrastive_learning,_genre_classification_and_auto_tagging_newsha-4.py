    ds = ds.map(lambda p, l: tf_safe_mel(p, l), num_parallel_calls=AUTOTUNE)
    ds = ds.filter(lambda x, y, ok: ok)
    ds = ds.map(lambda x, y, ok: (x, y), num_parallel_calls=AUTOTUNE)
    return ds

